let selected = scenarios[0];
let runToken = 0;
let replayState = 'idle';
let playbookIds = new Set(['helpful-pdf', 'shadow-invoice']);

const fieldDefinitions = [
  ['family', 'The category of threat story being rehearsed.'],
  ['surface', 'The part of the AI workflow where the issue could appear.'],
  ['fixture', 'The safe, fake input used for this local rehearsal.'],
  ['decision', 'The guard result: a blocked fixture outcome, an allowed control, or a shadow-only review.'],
  ['execution', 'Whether executable code actually ran. This lab should show not-run.'],
  ['target', 'Whether the fictional destination received an action. Blocked cases should show not reached.'],
  ['evidence', 'The supporting record used to explain the decision. [redacted] means raw hostile content is hidden and only safe labels or metadata are shown.'],
  ['boundary', 'The trust rule that prevents untrusted content from becoming authority.'],
  ['pairing', `Whether CanaryNorth has a current defense mapping for this rehearsal. The active private map has ${activePairingCount} passing checks; ${dormantVariantCount} dormant variants are excluded by default.`]
];

/* Seven authored beats. Nothing here runs; each line is a record, not an action. */
const replayBeats = [
  ['fixture selected', 'CATALOG'],
  ['redacted input loaded, raw content withheld', 'INPUT'],
  ['untrusted content normalized, kept outside authority', 'NORMALIZE'],
  ['policy result recorded', 'POLICY'],
  ['no code executed', 'ACTION'],
  ['target not reached', 'TARGET'],
  ['redacted ledger prepared', 'RECEIPT']
];

const reducedMotion = () => window.matchMedia('(prefers-reduced-motion: reduce)').matches;
const wait = (milliseconds) => new Promise((resolve) => setTimeout(resolve, reducedMotion() ? 0 : milliseconds));

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[character]));
}

function setTerminalState(label, tone = 'idle') {
  terminalState.textContent = label;
  terminalState.dataset.tone = tone;
}

function safeStatus(value) {
  return value === 'blocked' ? 'blocked fixture' : value === 'allowed' ? 'allowed control' : 'shadow-only review';
}

function verdictFor(scenario) {
  if (scenario.status === 'blocked') return { label: 'BLOCKED SAFELY', tone: 'blocked', note: 'authored fixture outcome, not proof of a production defense' };
  if (scenario.status === 'allowed') return { label: 'ALLOWED CONTROL', tone: 'allowed', note: 'authored control case, allowed by design' };
  return { label: 'REVIEW ONLY', tone: 'review', note: 'watched and reported, nothing is automatically prevented' };
}

function pairingFor(scenario) {
  return activePairingIds.has(scenario.id)
    ? 'connected CanaryNorth evaluator with passing paired test'
    : 'no public pairing claim';
}

function playbookCases() {
  return scenarios.filter((scenario) => playbookIds.has(scenario.id));
}

function generateSafePlaybookCode(cases) {
  const manifest = cases.map((scenario, index) => ({
    order: index + 1,
    id: scenario.id,
    name: scenario.name,
    family: scenario.family,
    expectedDecision: safeStatus(scenario.status),
    executionStatus: 'not-run',
    targetReached: false
  }));
  return `// Generated by PenTel Private Synthetic Lab\n// Defensive rehearsal only. No network, file, payload, or target execution.\n\nconst syntheticPlaybook = Object.freeze(${JSON.stringify({
    playbookId: `synthetic-chain-${cases.map((scenario) => scenario.id).join('-')}`,
    mode: 'shadow-only',
    syntheticOnly: true,
    executionStatus: 'not-run',
    externalContacted: false,
    cases: manifest
  }, null, 2)});\n\nexport function recordSyntheticPlaybook() {\n  return syntheticPlaybook.cases.map((step) => ({\n    ...step,\n    evidence: '[redacted]',\n    action: 'record-only'\n  }));\n}`;
}

function renderPlaybookBuilder() {
  const query = playbookFilter.value.trim().toLowerCase();
  const candidates = scenarios.filter((scenario) => scenario.status !== 'allowed'
    && `${scenario.name} ${scenario.family}`.toLowerCase().includes(query));
  playbookOptions.setAttribute('aria-label', 'matching synthetic cases');
  playbookOptions.innerHTML = candidates.map((scenario) => `<label class="playbook-option"><input type="checkbox" data-playbook-id="${escapeHtml(scenario.id)}" ${playbookIds.has(scenario.id) ? 'checked' : ''}><span><b>${escapeHtml(scenario.name)}</b><small>${escapeHtml(scenario.family)} / ${escapeHtml(scenario.status)}</small></span></label>`).join('');
  playbookOptions.querySelectorAll('input').forEach((input) => input.addEventListener('change', () => {
    if (input.checked && playbookIds.size >= 4) {
      input.checked = false;
      copyStatus.textContent = 'maximum four cases';
      announce('Four-case limit reached. Remove one case before adding another.', 'attention');
      return;
    }
    if (input.checked) playbookIds.add(input.dataset.playbookId);
    else playbookIds.delete(input.dataset.playbookId);
    renderPlaybookPreview();
    announce(`${playbookIds.size} synthetic case${playbookIds.size === 1 ? '' : 's'} selected for the playbook.`);
  }));
  renderPlaybookPreview();
}

function renderPlaybookPreview() {
  const cases = playbookCases();
  playbookCount.textContent = `${cases.length} selected`;
  playbookSequence.innerHTML = cases.length
    ? cases.map((scenario, index) => `<span class="playbook-step"><i>${index + 1}</i><span><b>${escapeHtml(scenario.name)}</b><small>${escapeHtml(scenario.status)}</small></span></span>`).join('<em>&rarr;</em>')
    : '<span class="playbook-empty">select at least one case</span>';
  generatedCode.value = cases.length ? generateSafePlaybookCode(cases) : '// Select a synthetic case to generate a safe manifest.';
  generatorState.textContent = cases.length ? 'LIVE PREVIEW' : 'WAITING FOR INPUT';
  codeState.textContent = cases.length ? 'NOT RUN' : 'EMPTY';
  codeState.dataset.state = 'idle';
  copyPlaybookButton.disabled = !cases.length;
  copyPlaybookButton.setAttribute('aria-disabled', String(!cases.length));
  if (!cases.length) copyStatus.textContent = 'select a case before copying';
}

function renderList() {
  const query = search.value.trim().toLowerCase();
  const visible = scenarios.filter((scenario) => (status.value === 'all' || scenario.status === status.value)
    && `${scenario.name} ${scenario.family}`.toLowerCase().includes(query));
  visibleCount.textContent = `${visible.length} visible`;
  catalogCount.textContent = 'ACTIVE';
  catalogHealth.textContent = visible.length ? 'READY' : 'NO MATCH';
  list.innerHTML = visible.length
    ? visible.map((scenario, index) => `<button class="terminal-item ${scenario.id === selected.id ? 'selected' : ''}" data-id="${escapeHtml(scenario.id)}" data-status="${escapeHtml(scenario.status)}" aria-pressed="${scenario.id === selected.id}" type="button">${String(index + 1).padStart(2, '0')} ${escapeHtml(scenario.name)}<small>${escapeHtml(scenario.status)} / ${escapeHtml(scenario.family)}</small></button>`).join('')
    : '<p class="no-results">No case matches this filter.</p>';
  list.querySelectorAll('button').forEach((button) => button.addEventListener('click', () => {
    runToken += 1;
    replayState = 'idle';
    selected = scenarios.find((scenario) => scenario.id === button.dataset.id) || selected;
    setTerminalState('CASE LOADED', 'loaded');
    renderList();
    renderStage();
    renderLedger();
    announce(`${selected.name} loaded. Its redacted record is shown on the evidence stage.`);
  }));
}

function renderStage() {
  const decision = safeStatus(selected.status);
  const guide = fieldDefinitions.map(([label, meaning]) => `<div><b>${escapeHtml(label)}</b><span>${escapeHtml(meaning)}</span></div>`).join('');
  const beats = replayBeats.map(([line, tag], index) => `<div class="replay-beat" data-beat="${index}"><i>${String(index + 1).padStart(2, '0')}</i><b>${escapeHtml(line)}</b><em>${escapeHtml(tag)}</em></div>`).join('');
  output.innerHTML = `
    <div class="command-line"><span class="terminal-prompt">&gt;</span> inspect --case ${escapeHtml(selected.id)} --mode redacted</div>
    <h2>${escapeHtml(selected.name)}</h2>
    <div class="case-family">${escapeHtml(selected.family)} / ${escapeHtml(selected.status)}</div>
    <p>${escapeHtml(selected.summary)}</p>
    <div class="terminal-stage" aria-label="Safe decision path">
      <span class="stage-step is-active"><i></i>INPUT</span>
      <span class="stage-step"><i></i>POLICY</span>
      <span class="stage-step"><i></i>REPORT</span>
    </div>
    <div class="terminal-kv">
      <b>surface</b><span>${escapeHtml(selected.surface || 'synthetic AI workflow')}</span>
      <b>fixture</b><span>${escapeHtml(selected.safeFixture || 'metadata-only synthetic case')}</span>
      <b>boundary</b><span>${escapeHtml(selected.boundary || 'Untrusted content cannot become authority.')}</span>
      <b>decision</b><span>${escapeHtml(decision)}</span>
      <b>execution</b><span>not-run</span>
      <b>target</b><span>fictional PenTel only, not reached</span>
      <b>evidence</b><span><span class="redacted">REDACTED</span> safe metadata only</span>
      <b>pairing</b><span>${escapeHtml(pairingFor(selected))}</span>
    </div>
    <details class="field-guide"><summary>What do these fields mean?</summary><div class="field-guide-grid">${guide}</div></details>
    <div class="terminal-actions">
      <button class="terminal-button" id="rehearse" data-tooltip="Replay the seven authored beats. Nothing executes." title="Replay the seven authored beats. Nothing executes." type="button">run replay</button>
      <button class="terminal-button danger-button" id="clear" data-tooltip="Cancel the active replay and reset only the local output." title="Cancel the active replay and reset only the local output." type="button">clear</button>
    </div>
    <div class="rehearsal-progress" aria-hidden="true"><i id="progress-bar"></i></div>
    <div class="replay-beats" id="replay-beats" aria-live="polite">${beats}</div>
    <div class="replay-verdict" id="replay-verdict" data-tone="idle" hidden></div>`;
  document.querySelector('#rehearse').addEventListener('click', () => runSafePath());
  document.querySelector('#clear').addEventListener('click', () => {
    runToken += 1;
    replayState = 'idle';
    setTerminalState('REHEARSAL IDLE');
    renderStage();
    renderLedger();
    announce('Local replay output cleared. The case index is unchanged.');
  });
}

function renderLedger() {
  const verdict = verdictFor(selected);
  const rows = [
    ['case', selected.id, false],
    ['decision', safeStatus(selected.status), false],
    ['execution', 'not-run', true],
    ['external-contacted', 'false', true],
    ['target-reached', 'false', true],
    ['evidence', '[redacted]', true],
    ['control pairing', pairingFor(selected), false],
    ['state', 'browser-local', true]
  ];
  ledger.innerHTML = `
    <div class="ledger-head"><span>Truth ledger</span><i>CHAIN OF CUSTODY</i></div>
    <div class="ledger-case">${escapeHtml(selected.name)}</div>
    <div class="ledger-rows">
      ${rows.map(([label, value, negative]) => `<div class="ledger-row"><b>${escapeHtml(label)}</b><span class="${negative ? 'is-negative' : ''}">${escapeHtml(value)}</span></div>`).join('')}
    </div>
    <div class="ledger-row"><b>replay</b><span class="is-negative" id="ledger-replay">${escapeHtml(replayState)}</span></div>
    <p class="ledger-note">${escapeHtml(verdict.note)}</p>
    <div class="ledger-seal">Evidence withheld by design</div>`;
}

async function runSafePath() {
  const token = ++runToken;
  const rehearseButton = document.querySelector('#rehearse');
  const progressBar = document.querySelector('#progress-bar');
  const beatRows = [...document.querySelectorAll('.replay-beat')];
  const verdictBand = document.querySelector('#replay-verdict');
  const stageSteps = [...document.querySelectorAll('.stage-step')];
  const verdict = verdictFor(selected);

  rehearseButton.disabled = true;
  replayState = 'running';
  beatRows.forEach((row) => row.classList.remove('is-on'));
  verdictBand.hidden = true;
  progressBar.style.width = '0%';
  setTerminalState('REHEARSAL RUNNING', 'running');
  renderLedger();
  announce(`Safe replay started for ${selected.name}. Nothing will execute.`);

  for (const [index, row] of beatRows.entries()) {
    await wait(300);
    if (token !== runToken) return;
    row.classList.add('is-on');
    progressBar.style.width = `${Math.round(((index + 1) / beatRows.length) * 100)}%`;
    const stageIndex = index < 2 ? 0 : index < 5 ? 1 : 2;
    stageSteps.forEach((step, stepIndex) => {
      step.classList.toggle('is-active', stepIndex === stageIndex);
      step.classList.toggle('is-complete', stepIndex < stageIndex);
    });
  }

  verdictBand.dataset.tone = verdict.tone;
  verdictBand.innerHTML = `<span>${escapeHtml(verdict.label)}</span><small>${escapeHtml(verdict.note)}</small>`;
  verdictBand.hidden = false;
  setTerminalState(verdict.label, verdict.tone);
  stageSteps.forEach((step) => { step.classList.remove('is-active'); step.classList.add('is-complete'); });
  rehearseButton.disabled = false;
  replayState = 'complete';
  renderLedger();
  announce(`${selected.name} finished safely. The redacted receipt is ready.`, 'success');
}

