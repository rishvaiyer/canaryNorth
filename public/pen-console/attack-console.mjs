document.querySelectorAll('.command-chip').forEach((button) => button.addEventListener('click', () => {
  document.querySelectorAll('.command-chip').forEach((chip) => {
    chip.classList.toggle('active', chip === button);
    chip.setAttribute('aria-pressed', String(chip === button));
  });
  if (button.dataset.command === 'compose') {
    playbookBuilder.open = true;
    playbookBuilder.scrollIntoView({ behavior: reducedMotion() ? 'auto' : 'smooth', block: 'start' });
    announce('Playbook workbench opened. Choose up to four synthetic cases.');
  }
  if (button.dataset.command === 'inspect') {
    window.scrollTo({ top: 0, behavior: reducedMotion() ? 'auto' : 'smooth' });
    announce(`Inspect mode selected. Showing ${selected.name}.`);
  }
  if (button.dataset.command === 'rehearse') document.querySelector('#rehearse')?.click();
}));

document.addEventListener('keydown', (event) => {
  const tag = document.activeElement?.tagName;
  const inField = tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT';
  if (event.key === '/' && !inField) { event.preventDefault(); search.focus(); }
  if (event.key.toLowerCase() === 'r' && !inField && !document.querySelector('#rehearse')?.disabled) document.querySelector('#rehearse')?.click();
});

