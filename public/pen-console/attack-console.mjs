generatePlaybookButton.addEventListener('click', () => {
  const cases = playbookCases();
  if (!cases.length) {
    copyStatus.textContent = 'select a case first';
    announce('Select at least one synthetic case before generating.', 'attention');
    return;
  }
  renderPlaybookPreview();
  copyStatus.textContent = `${cases.length} synthetic cases composed`;
  generatorState.textContent = 'MANIFEST READY';
  codeState.textContent = 'READY TO COPY';
  codeState.dataset.state = 'ready';
  setTerminalState('MANIFEST READY', 'loaded');
  announce(`${cases.length}-case inert playbook generated. It is ready to copy.`, 'success');
});

copyPlaybookButton.addEventListener('click', async () => {
  if (!generatedCode.value || generatedCode.value.startsWith('// Select')) {
    copyStatus.textContent = 'Nothing to copy yet';
    announce('Nothing to copy yet. Select a case and generate the playbook first.', 'attention');
    return;
  }
  try {
    await navigator.clipboard.writeText(generatedCode.value);
    copyStatus.textContent = 'copied inert manifest';
    announce('Inert manifest copied to the local clipboard.', 'success');
  } catch {
    generatedCode.select();
    copyStatus.textContent = 'manifest selected for local copy';
    announce('Clipboard access was unavailable, so the inert manifest was selected for manual copy.', 'attention');
  }
});
